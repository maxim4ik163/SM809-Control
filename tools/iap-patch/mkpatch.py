#!/usr/bin/env python3
"""Generate patch_data.go: the difference between the vendor updater
SM809_Mouse_Wired_USB_IAP25-08-11-1.exe and our patched updater
(zones firmware = d64 LED fix + lighting zones, English UI, forced update,
30 s reconnect wait). Only changed bytes and the appended English resources
go into the repo; the vendor binary itself does not.

usage: mkpatch.py ORIGINAL.exe PATCHED.exe > patch_data.go
"""
import hashlib, sys, base64
a = open(sys.argv[1], 'rb').read()
b = open(sys.argv[2], 'rb').read()
assert len(b) >= len(a)
runs, i, n = [], 0, len(a)
while i < n:
    if a[i] != b[i]:
        j = i
        # merge runs closer than 8 bytes
        while j < n and (a[j] != b[j] or a[j:j+8] != b[j:j+8]):
            j += 1
        runs.append((i, b[i:j])); i = j
    else:
        i += 1
out = ['// Code generated by mkpatch.py; DO NOT EDIT.', '', 'package main', '',
       'const (',
       f'\torigSize = {len(a)}',
       f'\torigSHA256 = "{hashlib.sha256(a).hexdigest()}"',
       f'\tresultSize = {len(b)}',
       f'\tresultSHA256 = "{hashlib.sha256(b).hexdigest()}"',
       ')', '',
       'var runs = []run{']
for off, data in runs:
    out.append(f'\t{{0x{off:x}, "{data.hex()}"}},')
out += ['}', '', f'var tailB64 = "{base64.b64encode(b[n:]).decode()}"', '']
print('\n'.join(out))
